#!/usr/bin/env python3
"""Convert a KLEE klee_dump_expr value dump into a result definition.

The RVT KLEE fork's klee_dump_expr writes, per explored path:

    <KLEE_DUMP_DIR>/<tag>.<state-id>.smt2      value expression
        (assert (= (_ bv0 W) EXPR))
    <KLEE_DUMP_DIR>/<tag>.<state-id>.pc.smt2   path condition
        (assert (and true c1 c2 ...))

This script extracts EXPR and emits a file with

    (define-fun result () (_ BitVec W) EXPR)

keeping the array declarations, so that dumps from two different
implementations (C and Rust, or Rust and Rust) can be combined into a
single equivalence query.

Usage: klee-dump-to-def.py INPUT.smt2 OUTPUT.smt2 [--name NAME] [--width W]
"""
import argparse
import re
import sys
from pathlib import Path


def sexp_tokens(text):
    return re.findall(r'\(|\)|[^\s()]+', text)


def parse_sexp(tokens, i=0):
    assert tokens[i] == '('
    i += 1
    out = []
    while tokens[i] != ')':
        if tokens[i] == '(':
            node, i = parse_sexp(tokens, i)
            out.append(node)
        else:
            out.append(tokens[i])
            i += 1
    return out, i + 1


def find_assert_expr(node):
    if not isinstance(node, list):
        return None
    if node and node[0] == 'assert':
        return node[1]
    for child in node:
        r = find_assert_expr(child)
        if r is not None:
            return r
    return None


def is_zero_bv(node):
    if isinstance(node, list):
        return len(node) == 3 and node[0] == '_' and node[1] == 'bv0'
    return node.startswith('(_ bv0 ')


def strip_outer_zero_eq(node):
    """Strip ONLY the dump's outer `(= (_ bv0 W) EXPR)` wrapper.

    KLEE normalizes `x != 0` into `(= false (= (_ bv0 W) x))`, so inner
    `(= (_ bv0 W) ...)` occurrences are real program semantics and must
    be preserved.  The dump printer emits let-bindings for shared
    sub-expressions, so the wrapper may sit inside a `(let ...)` form;
    the bindings are carried along so the result stays self-contained."""
    if (isinstance(node, list) and len(node) == 3 and node[0] == '='
            and is_zero_bv(node[1])):
        return node[2]
    if (isinstance(node, list) and len(node) >= 3 and node[0] == 'let'
            and isinstance(node[2], list) and len(node[2]) == 3
            and node[2][0] == '=' and is_zero_bv(node[2][1])):
        return ['let', node[1], node[2][2]]
    return node


def replace_eq_zero(node):
    """Replace (= (_ bv0 W) EXPR) with EXPR inside an expression tree."""
    if not isinstance(node, list):
        return node
    if len(node) == 3 and node[0] == '=' and is_zero_bv(node[1]):
        return replace_eq_zero(node[2])
    return [replace_eq_zero(x) for x in node]


def expr_to_str(node):
    if isinstance(node, list):
        return '(' + ' '.join(expr_to_str(x) for x in node) + ')'
    return node


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('input')
    ap.add_argument('output')
    ap.add_argument('--name', default='result')
    ap.add_argument('--width', type=int, default=None)
    args = ap.parse_args()

    text = Path(args.input).read_text()
    tokens = sexp_tokens(text)
    forms = []
    i = 0
    while i < len(tokens):
        if tokens[i] == '(':
            node, i = parse_sexp(tokens, i)
            forms.append(node)
        else:
            i += 1
    assert_node = None
    for root in forms:
        assert_node = find_assert_expr(root)
        if assert_node is not None:
            break
    if assert_node is None:
        print('no assert found', file=sys.stderr)
        return 2
    expr = strip_outer_zero_eq(assert_node)

    width = args.width
    if width is None:
        # The width comes from the OUTER wrapper, not from any inner
        # `(_ bv0 W)` constants inside let-bindings.
        width = 64
        node = unwrap_lets(assert_node)
        if (isinstance(node, list) and len(node) == 3 and node[0] == '='
                and is_zero_bv(node[1])):
            width = int(node[1][2]) if len(node[1]) == 3 else width

    keep = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith('(set-logic') or stripped.startswith('(declare-fun'):
            keep.append(line)

    out = ['; generated by klee-dump-to-def.py'] + keep
    out.append(f'(define-fun {args.name} () (_ BitVec {width}) '
               f'{expr_to_str(expr)})')
    Path(args.output).write_text('\n'.join(out) + '\n')
    print(f'wrote {args.output} width={width}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
